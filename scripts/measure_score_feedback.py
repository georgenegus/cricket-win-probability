# 3. monotone-constraint audit + feature importance
# ----------------------------------------------------------------------------------------

def audit_model(model: DeliveryOutcomeModel) -> dict:
    """What constraints are actually on the trained booster, and what does it lean on."""
    out = {}
    for head in ("extras", "legal"):
        clf = model.final_model.get(head)
        if clf is None:
            continue
        params = clf.get_params()
        mc = params.get("monotone_constraints")
        try:
            booster_mc = clf.get_booster().save_config()
            has_mc = '"monotone_constraints":"()"' not in booster_mc and "monotone_constraints" in booster_mc
        except Exception:
            has_mc = None
        out[head] = {
            "monotone_constraints_param": mc if mc is not None else "None (unconstrained)",
            "interaction_constraints_param": params.get("interaction_constraints") or "None",
            "max_depth": params.get("max_depth"),
            "n_estimators": params.get("n_estimators"),
            "min_child_weight": params.get("min_child_weight"),
            "booster_config_mentions_constraints": has_mc,
        }
    legal = model.final_model.get("legal")
    if legal is not None:
        gain = legal.get_booster().get_score(importance_type="gain")
        # XGBoost keys features as f0..fN when fitted from a numpy array.
        named = {}
        for k, v in gain.items():
            idx = int(k[1:]) if k.startswith("f") and k[1:].isdigit() else None
            named[FEATURES[idx] if idx is not None and idx < len(FEATURES) else k] = float(v)
        total = sum(named.values()) or 1.0
        out["legal_gain_importance"] = {
            k: {"gain": round(v, 2), "share": round(v / total, 4)}
            for k, v in sorted(named.items(), key=lambda kv: -kv[1])
        }
    return out


# ----------------------------------------------------------------------------------------
# 4. ablation
# ----------------------------------------------------------------------------------------

def _variant_features(variant: str):
    """FEATURES with current_team_score kept / removed / replaced, order otherwise untouched.

    Column ORDER is preserved deliberately: XGBoost's colsample_bytree is sensitive to it
    under a fixed seed, so reordering would confound the ablation with a sampling change.
    """
    if variant == "control":
        return list(FEATURES)
    if variant == "drop":
        return [f for f in FEATURES if f != SCORE_COL]
    if variant == "replace":
        return [REPLACEMENT_COL if f == SCORE_COL else f for f in FEATURES]
    raise ValueError(variant)


def run_ablation(fmt: str, frame: pd.DataFrame, traj_vecs: dict, n_matches: int,
                 n_folds_used: int, n_splits: int = 5, seed: int = 42) -> dict:
    """OOF log-loss for the legal-outcome head under control / drop / replace.

    Subsampled by MATCH (never by delivery -- splitting a match across train and validation is
    the leakage rule this codebase cares about most), then GroupKFold by match_id exactly as
    DeliveryOutcomeModel.fit does. Hyperparameters are left identical to production: the point
    is to price the feature, and changing the model alongside it would price something else.

    Only `n_folds_used` of the `n_splits` folds are actually trained -- each fold is an
    independent OOF estimate, so trading folds for wall-clock is a precision decision, not a
    validity one. Every variant sees the same matches, the same splits and the same rows.
    """
    matches = frame["match_id"].unique()
    rng = np.random.default_rng(seed)
    if n_matches and len(matches) > n_matches:
        matches = rng.choice(matches, size=n_matches, replace=False)
    # Subsample BEFORE copying -- materialising all ~2.3M legal rows only to throw 80% away
    # is the difference between fitting in RAM and swapping on this box.
    legal = frame[(frame["extra_class"] == "legal")
                  & frame["match_id"].isin(matches)].reset_index(drop=True)
    legal[REPLACEMENT_COL] = apply_trajectory(legal, traj_vecs)

    y = legal["legal_outcome"].map(LEGAL_CLASS_TO_IDX).values
    groups = legal["match_id"].values
    gkf = GroupKFold(n_splits=n_splits)
    splits = list(gkf.split(legal, y, groups=groups))[:n_folds_used]
    n_scored = sum(len(v) for _, v in splits)

    print(f"    ablation corpus: {len(legal):,} legal deliveries over {len(matches):,} matches; "
          f"{n_folds_used}/{n_splits} folds -> {n_scored:,} scored OOF", flush=True)

    labels = list(range(len(LEGAL_CLASSES)))
    proto = DeliveryOutcomeModel(format_type=fmt, n_splits=n_splits, random_state=seed)

    results = {}
    per_row_ll = {}   # variant -> per-scored-row log-loss, aligned to `order`
    order = np.concatenate([v for _, v in splits])
    for variant in ("control", "drop", "replace"):
        cols = _variant_features(variant)
        X = legal[cols].values
        lls, chunks = [], []
        t0 = time.time()
        for fold_idx, (tr, va) in enumerate(splits):
            clf = proto._make_legal_clf()
            clf.fit(X[tr], y[tr])
            p = clf.predict_proba(X[va])
            lls.append(float(log_loss(y[va], p, labels=labels)))
            # Per-row log-loss of the true class, for the match-level paired test below.
            chunks.append(-np.log(np.clip(p[np.arange(len(va)), y[va]], 1e-15, None)))
            del clf
        per_row_ll[variant] = np.concatenate(chunks)
        results[variant] = {
            "oof_log_loss": float(np.average(lls, weights=[len(v) for _, v in splits])),
            "per_fold_log_loss": [round(x, 6) for x in lls],
            "n_features": len(cols),
            "fit_seconds": round(time.time() - t0, 1),
        }
        print(f"    {variant:8s} OOF legal log-loss = {results[variant]['oof_log_loss']:.6f} "
              f"({results[variant]['fit_seconds']:.0f}s)", flush=True)

    # Match-level paired test. Deliveries within a match are heavily correlated, so the match
    # is the unit of independence; pooling them here would manufacture significance.
    scored_matches = pd.Series(groups[order], name="match_id")
    control_ll = per_row_ll["control"]
    for variant in ("drop", "replace"):
        diff = pd.DataFrame({
            "match_id": scored_matches.values,
            "d": per_row_ll[variant] - control_ll,
        }).groupby("match_id")["d"].mean()
        se = diff.std(ddof=1) / np.sqrt(len(diff))
        results[variant]["delta_vs_control"] = round(
            results[variant]["oof_log_loss"] - results["control"]["oof_log_loss"], 6)
        results[variant]["match_paired"] = {
            "n_matches": int(len(diff)),
            "mean_delta": round(float(diff.mean()), 6),
            "se": round(float(se), 6),
            "t": round(float(diff.mean() / se), 2) if se > 0 else None,
            "share_worse": round(float((diff > 0).mean()), 3),
        }
    results["_meta"] = {
        "n_matches": int(len(matches)),
        "n_legal_deliveries": int(len(legal)),
        "n_scored_oof": int(n_scored),
        "n_folds_used": n_folds_used,
        "n_splits": n_splits,
    }
    return results


