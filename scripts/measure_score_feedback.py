"""
Phase 0 of mc_runrate_feedback_plan.md -- characterise the `current_team_score` feedback loop.

`current_team_score` is both an INPUT to the delivery-outcome model and an OUTPUT of the
simulator. In training that is legitimate (a high score at a given point genuinely predicts
continued fast scoring); inside a simulation it is circular -- the score is generated by the
model's own assumptions, then fed back as evidence about conditions it invented.

This script ships NOTHING. It measures the four things that gate Phase 1/2's design:

  1. SENSITIVITY   -- perturb `current_team_score` by a fixed delta on real out-of-fold states
                      and read off d(runs per over) / d(run of score), per format. This is the
                      loop's gain: multiply it by the measured score drift to get the run-rate
                      excess the loop explains.
  2. SHAPE         -- partial dependence of E[runs] on `current_team_score` across its real
                      range, globally and within over buckets (a global grid is badly
                      off-distribution -- 300 runs at ball 10 does not occur, so a global-only
                      curve mostly measures extrapolation). A smooth, economically sensible
                      curve is real signal to preserve; a steep or non-monotonic one argues for
                      regularisation.
  3. ABLATION COST -- retrain the legal-outcome head out-of-fold with `current_team_score`
                      (a) dropped and (b) replaced by `score_minus_par_trajectory`, and report
                      the log-loss delta. Phase 2 is only viable if that cost is small.
  4. AUDIT         -- monotone constraints actually in force on the trained booster, plus gain
                      feature importance for context.

As a by-product it measures the per-format PAR SCORE TRAJECTORY (mean cumulative score at each
legal-ball index) that variant (b) needs -- which is also the vector Phase 1's damping requires,
so it is written out to outputs/ rather than recomputed there.

METHODOLOGY NOTES (both learned the hard way on this plan):

  * The ablation delta is measured against a CONTROL variant retrained on the same subsample
    and the same folds, never against the full-corpus lock in sim_baseline_metrics.json. A
    subsampled retrain is worse than the lock for reasons that have nothing to do with the
    feature, so only the control-relative delta is interpretable. The locked numbers are printed
    alongside purely as context.
  * Significance is assessed with the MATCH as the unit of independence (per-match mean
    log-loss, paired across variants). Pooling correlated deliveries on this plan has already
    turned a 1-SE difference into an apparent 5.8-SE finding once. |t| > 2 is the bar.

Run:
    py scripts/measure_score_feedback.py --formats od t20
    py scripts/measure_score_feedback.py --formats od --skip-ablation     # fast pass
"""

