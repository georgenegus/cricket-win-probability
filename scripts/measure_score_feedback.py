def load_model(fmt: str) -> DeliveryOutcomeModel:
    cache_path = PROJECT_ROOT / "data" / "processed" / f"{fmt}_delivery_outcome_model.pkl"
    if not cache_path.exists():
        raise FileNotFoundError(
            f"No trained sim model at {cache_path} -- run retrain_full('{fmt}') first."
        )
    model = DeliveryOutcomeModel(format_type=fmt)
    model.fit(None, cache_path=cache_path)  # cache exists -> loads fold models, no training
    return model


def prepare_frame(fmt: str, model: DeliveryOutcomeModel) -> pd.DataFrame:
    """build_frame + the fold assignment, exactly as the sim_baseline_metrics gate does it."""
    frame = build_frame(fmt)
    frame["_fold"] = frame["match_id"].map(model.match_to_fold)
    frame = frame.dropna(subset=["_fold"]).copy()
    frame["_fold"] = frame["_fold"].astype(int)
    # Legal-ball index BEFORE this delivery, within match+innings. This is the same quantity
    # the simulator carries as `legal_balls`, so a trajectory indexed by it lines up exactly
    # between training rows and simulated rows.
    is_legal = (frame["extra_class"] == "legal").astype(np.int32)
    frame["legal_balls_before"] = (
        is_legal.groupby([frame["match_id"], frame["innings"]]).cumsum() - is_legal
    ).astype(np.int32)
    # Drop everything this script never reads. build_frame carries the raw delivery columns
    # (batter/bowler/venue/competition name strings), which on a 2.4M-row t20 corpus is most of
    # the frame's footprint -- and this box has 7.7GB.
    keep = list(dict.fromkeys(
        FEATURES + ["match_id", "innings", "extra_class", "legal_outcome",
                    "over_float", "legal_balls_before", "_fold"]
    ))
    return frame[keep]


def oof_legal_proba(model: DeliveryOutcomeModel, df: pd.DataFrame,
                    features=None) -> np.ndarray:
    """(N, 7) legal-outcome probabilities, each row scored by the fold model that did NOT
    train on its match. Rows whose fold has no model are left as NaN.

    `features` is an explicit override for the SCORE_COL drop/replace ablation variants below
    (t20/od only, never a DELIVERY_OUTCOME_POOL_SOURCE format) -- the default (None) path goes
    through model.oof_features(), which synthesizes is_hundred for a pooled model (hnd) so this
    still works after the 2026-08-12 pooling change."""
    X = (model.oof_features(df) if features is None else df[list(features)]).values
    out = np.full((len(df), len(LEGAL_CLASSES)), np.nan)
    folds = df["_fold"].values
    for fold_idx, pack in model.fold_models.items():
        m = folds == fold_idx
        if m.any():
            out[m] = pack["legal"].predict_proba(X[m])
    return out


def sample_legal(frame: pd.DataFrame, n: int, seed: int = 42) -> pd.DataFrame:
    """A reproducible sample of legal deliveries, used for the perturbation/PD passes."""
    legal = frame[frame["extra_class"] == "legal"]
    if n and len(legal) > n:
        legal = legal.sample(n=n, random_state=seed)
    return legal.reset_index(drop=True)


# ----------------------------------------------------------------------------------------
# 0. par score trajectory (needed by ablation variant (b); reused by Phase 1)
# ----------------------------------------------------------------------------------------

def measure_score_trajectory(frame: pd.DataFrame, fmt: str) -> dict:
    """Mean cumulative score at each legal-ball index, per innings.

    Two variants are measured because they answer subtly different questions:

      full_length -- restricted to innings that used their whole quota or were bowled out,
                     mirroring BOWLER_OVER_SHARES's methodology so rain-shortened innings
                     don't drag the tail down. This is the plan's specified definition and
                     the one the ablation uses.
      all_reaching -- every innings that reached the index, i.e. conditioned on "still
                     batting", which is the state the simulator is actually in when it looks
                     the trajectory up. Reported so Phase 1 can see how much survivorship
                     selection moves the curve before committing to a definition.

    Innings 2's full_length subset is a biased sample by construction (a chase that used all
    its balls is one that did not win comfortably), so its curve sits low. The model carries
    `innings` as a feature and can absorb a deterministic per-innings offset, but Phase 1
    should not read innings 2's curve as "expected chase score".
    """
    fmt_spec = spec(fmt)
    total_balls = int(fmt_spec["total_balls"])
    bpo = int(fmt_spec["balls_per_over"])

    out = {"format": fmt, "total_balls": total_balls, "balls_per_over": bpo, "innings": {}}
    for innings in (1, 2):
        sub = frame[frame["innings"] == innings]
        if sub.empty:
            continue
        per_innings = sub.groupby(["match_id", "innings"]).agg(
            max_ball=("legal_balls_before", "max"),
            wkts=("wickets_lost", "max"),
        )
        full_ids = per_innings[
            (per_innings["max_ball"] >= total_balls - bpo) | (per_innings["wkts"] >= 9)
        ].index
        full = sub.set_index(["match_id", "innings"]).loc[
            sub.set_index(["match_id", "innings"]).index.isin(full_ids)
        ].reset_index()

        curves = {}
        for label, src in (("full_length", full), ("all_reaching", sub)):
            g = src.groupby("legal_balls_before")[SCORE_COL].mean()
            # Reindex onto the full 0..total_balls-1 grid; indices no innings reached (or that
            # only extras-heavy innings reached) are forward-filled from the last observed
            # value, then back-filled at the head, so the vector is always dense.
            vec = g.reindex(range(total_balls)).ffill().bfill()
            curves[label] = [round(float(v), 4) for v in vec.values]
            curves[f"{label}_n_innings"] = int(src.groupby(["match_id", "innings"]).ngroups)
        out["innings"][str(innings)] = curves
    return out


def trajectory_vectors(traj: dict) -> dict:
    """{innings -> np.ndarray} of the full_length curve, for the ablation's variant (b)."""
    return {int(k): np.asarray(v["full_length"], dtype=np.float64)
            for k, v in traj["innings"].items()}


def apply_trajectory(df: pd.DataFrame, vecs: dict) -> np.ndarray:
    """current_team_score - par_trajectory[innings][legal_ball_index], row-wise."""
    idx = df["legal_balls_before"].values
    innings = df["innings"].values
    par = np.zeros(len(df), dtype=np.float64)
    for inn, vec in vecs.items():
        m = innings == inn
        if m.any():
            par[m] = vec[np.clip(idx[m], 0, len(vec) - 1)]
    return df[SCORE_COL].values.astype(np.float64) - par


# ----------------------------------------------------------------------------------------
# 1. sensitivity sweep
# ----------------------------------------------------------------------------------------

def _slope_summary(df: pd.DataFrame, target_delta: float = 10.68) -> dict:
    """Turns a (delta, d_rpo, d_p_wicket) table into slope + linearity statistics."""
    df = df.copy()
    df["rpo_per_run"] = np.where(df["delta"] != 0.0,
                                 df["d_rpo"] / df["delta"].replace(0, np.nan), np.nan)
    nz = df[df["delta"] != 0.0]
    # Linearity: a quadratic fit over the whole grid. If the response were linear the
    # quadratic term would be ~0; a large one means the slope quoted at +10 does not
    # transfer to +20, which changes how the loop's equilibrium should be modelled.
    quad = np.polyfit(df["delta"].values, df["d_rpo"].values, 2)
    lin = np.polyfit(df["delta"].values, df["d_rpo"].values, 1)
    return {
        "table": df.to_dict(orient="records"),
        "linear_slope_rpo_per_run": float(lin[0]),
        "quadratic_coef": float(quad[0]),
        "linear_slope_from_quadratic_fit": float(quad[1]),
        "slope_at_plus_10ish": float(nz.loc[nz["delta"].sub(target_delta).abs().idxmin(), "rpo_per_run"]),
        "p_wicket_slope_per_run": float(np.polyfit(df["delta"].values, df["d_p_wicket"].values, 1)[0]),
    }


def sensitivity_sweep(model, sample: pd.DataFrame, fmt: str, deltas) -> dict:
    """d(runs per over) and d(P(wicket)) per run added to current_team_score, on real states.

    The whole sample is shifted by each delta and rescored out-of-fold. Only the score column
    moves -- every other feature (including the mechanically-derived required_run_rate) is held
    at its real value, which deliberately isolates the CONDITIONS-PROXY channel from the
    mechanical ones.

    Reported globally AND per over bucket, because the pooled slope is not the loop's gain.
    A fixed +10 shift is a near-doubling at over 3 and a rounding error at over 45, so the
    pooled number is dominated by early-innings states the simulator has barely drifted in yet.
    The simulator's drift accumulates with the innings, so the LATE-innings slope is the one
    that governs the equilibrium; the pooled figure is kept only for continuity with the
    earlier od measurement.
    """
    bpo = int(spec(fmt)["balls_per_over"])
    n_overs = int(spec(fmt)["total_overs"])
    base_score = sample[SCORE_COL].values.astype(np.float64)

    edges = np.linspace(0, n_overs, 5)
    bucket = pd.cut(sample["over_float"], bins=[-1e-9] + list(edges[1:]),
                    labels=[f"{int(a)}-{int(b)}" for a, b in zip(edges[:-1], edges[1:])])

    per_row, rows = {}, []
    for d in deltas:
        work = sample.copy()
        # Scores cannot go negative; clipping keeps the -20 arm on-distribution at the start
        # of an innings instead of asking the model about an impossible state.
        work[SCORE_COL] = np.clip(base_score + d, 0.0, None)
        proba = oof_legal_proba(model, work)
        ok = ~np.isnan(proba[:, 0])
        exp_runs = np.where(ok, proba @ RUN_VALUE, np.nan)
        p_w = np.where(ok, proba[:, WICKET_IDX], np.nan)
        per_row[float(d)] = (exp_runs, p_w)
        rows.append({
            "delta": float(d),
            "mean_applied_delta": float((work[SCORE_COL].values - base_score)[ok].mean()),
            "exp_runs_per_ball": float(np.nanmean(exp_runs)),
            "exp_runs_per_over": float(np.nanmean(exp_runs) * bpo),
            "p_wicket": float(np.nanmean(p_w)),
            "n": int(ok.sum()),
        })
        print(f"    delta {d:+7.2f} -> {rows[-1]['exp_runs_per_over']:.4f} rpo, "
              f"P(W) {rows[-1]['p_wicket']:.5f}", flush=True)

    df = pd.DataFrame(rows)
    base = df.loc[df["delta"] == 0.0].iloc[0]
    df["d_rpo"] = df["exp_runs_per_over"] - base["exp_runs_per_over"]
    df["d_p_wicket"] = df["p_wicket"] - base["p_wicket"]

    out = _slope_summary(df)
    out["n_states"] = int(len(sample))

    out["by_over_bucket"] = {}
    for label in bucket.cat.categories:
        m = (bucket == label).values
        if m.sum() < 500:
            continue
        brows = []
        for d, (exp_runs, p_w) in per_row.items():
            brows.append({
                "delta": float(d),
                "exp_runs_per_over": float(np.nanmean(exp_runs[m]) * bpo),
                "p_wicket": float(np.nanmean(p_w[m])),
            })
        bdf = pd.DataFrame(brows)
        b0 = bdf.loc[bdf["delta"] == 0.0].iloc[0]
        bdf["d_rpo"] = bdf["exp_runs_per_over"] - b0["exp_runs_per_over"]
        bdf["d_p_wicket"] = bdf["p_wicket"] - b0["p_wicket"]
        s = _slope_summary(bdf)
        s["n"] = int(m.sum())
        s["mean_real_score"] = float(sample.loc[m, SCORE_COL].mean())
        out["by_over_bucket"][str(label)] = s
    return out


# ----------------------------------------------------------------------------------------
# 2. partial dependence shape
# ----------------------------------------------------------------------------------------

def partial_dependence(model, sample: pd.DataFrame, fmt: str, n_grid: int = 9) -> dict:
    """E[runs/over] as current_team_score is swept across its real range.

    Reported globally AND within over buckets. The global curve is the conventional PD but is
    heavily off-distribution at both ends (300 runs at ball 10 never happens), so the bucketed
    curves -- each swept only over the scores actually observed in that bucket -- are the ones
    that say whether the learned response is economically sensible.
    """
    bpo = int(spec(fmt)["balls_per_over"])
    n_overs = int(spec(fmt)["total_overs"])
    qs = np.linspace(0.05, 0.95, n_grid)

    def _curve(sub: pd.DataFrame, grid: np.ndarray) -> list:
        pts = []
        for v in grid:
            work = sub.copy()
            work[SCORE_COL] = float(v)
            proba = oof_legal_proba(model, work)
            ok = ~np.isnan(proba[:, 0])
            if not ok.any():
                continue
            pts.append({
                "score": round(float(v), 2),
                "exp_runs_per_over": float((proba[ok] @ RUN_VALUE).mean() * bpo),
                "p_wicket": float(proba[ok, WICKET_IDX].mean()),
            })
        return pts

    global_grid = np.quantile(sample[SCORE_COL].values, qs)
    out = {"global": _curve(sample, global_grid), "by_over_bucket": {}}

    # Four buckets spanning the innings; each keeps enough rows for a stable mean.
    edges = np.linspace(0, n_overs, 5)
    for lo, hi in zip(edges[:-1], edges[1:]):
        sub = sample[(sample["over_float"] >= lo) & (sample["over_float"] < hi)]
        if len(sub) < 500:
            continue
        sub = sub.sample(n=min(len(sub), 20000), random_state=7)
        grid = np.quantile(sub[SCORE_COL].values, qs)
        label = f"{int(lo)}-{int(hi)}"
        out["by_over_bucket"][label] = {
            "n": int(len(sub)),
            "score_range": [round(float(grid[0]), 1), round(float(grid[-1]), 1)],
            "curve": _curve(sub, grid),
        }
        c = out["by_over_bucket"][label]["curve"]
        if len(c) >= 2:
            span = c[-1]["score"] - c[0]["score"]
            out["by_over_bucket"][label]["slope_rpo_per_run"] = (
                (c[-1]["exp_runs_per_over"] - c[0]["exp_runs_per_over"]) / span if span else None
            )
            rpo = [p["exp_runs_per_over"] for p in c]
            out["by_over_bucket"][label]["monotone_increasing"] = bool(
                all(b >= a - 1e-9 for a, b in zip(rpo, rpo[1:]))
            )
    return out


