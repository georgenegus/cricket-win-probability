def run_format(fmt: str, args) -> dict:
    print("=" * 78)
    print(f"SCORE-FEEDBACK CHARACTERISATION -- {fmt.upper()}")
    print("=" * 78, flush=True)

    model = load_model(fmt)
    print("  building training frame (cache-aware)...", flush=True)
    frame = prepare_frame(fmt, model)
    print(f"  {len(frame):,} deliveries, {frame['match_id'].nunique():,} matches", flush=True)

    out = {"format": fmt, "n_deliveries": int(len(frame)),
           "n_matches": int(frame["match_id"].nunique())}

    print("\n  [audit] monotone constraints + gain importance")
    out["audit"] = audit_model(model)
    for head, info in out["audit"].items():
        if head == "legal_gain_importance":
            continue
        print(f"    {head:7s} monotone_constraints = {info['monotone_constraints_param']}")
    gi = out["audit"].get("legal_gain_importance", {})
    if SCORE_COL in gi:
        rank = list(gi).index(SCORE_COL) + 1
        print(f"    {SCORE_COL}: gain share {gi[SCORE_COL]['share']:.1%} "
              f"(rank {rank}/{len(gi)})")

    print("\n  [trajectory] par score by legal-ball index")
    traj = measure_score_trajectory(frame, fmt)
    out["trajectory_summary"] = {
        inn: {
            "full_length_n_innings": c["full_length_n_innings"],
            "all_reaching_n_innings": c["all_reaching_n_innings"],
            "full_length_final": c["full_length"][-1],
            "all_reaching_final": c["all_reaching"][-1],
        }
        for inn, c in traj["innings"].items()
    }
    for inn, s in out["trajectory_summary"].items():
        print(f"    innings {inn}: full-length curve ends at {s['full_length_final']:.1f} "
              f"(n={s['full_length_n_innings']:,}); all-reaching ends at "
              f"{s['all_reaching_final']:.1f} (n={s['all_reaching_n_innings']:,})")
    traj_path = OUT_DIR / f"score_trajectory_{fmt}.json"
    traj_path.parent.mkdir(parents=True, exist_ok=True)
    traj_path.write_text(json.dumps(traj, indent=2))
    print(f"    -> {traj_path}")

    sample = sample_legal(frame, args.sample_deliveries)
    print(f"\n  [sensitivity] perturbing {SCORE_COL} on {len(sample):,} real OOF states")
    out["sensitivity"] = sensitivity_sweep(model, sample, fmt, args.deltas)
    s = out["sensitivity"]
    print(f"    pooled linear slope: {s['linear_slope_rpo_per_run']:+.5f} rpo per run of score")
    print(f"    pooled at +10.68   : {s['slope_at_plus_10ish']:+.5f} rpo per run")
    print(f"    quadratic coef     : {s['quadratic_coef']:+.3e} (~0 => linear response)")
    print(f"    P(W) slope         : {s['p_wicket_slope_per_run']:+.3e} per run")
    print(f"    {'overs':>8s} {'n':>8s} {'mean score':>11s} {'rpo/run':>10s} {'@+10.68':>10s} {'quad':>11s}")
    for label, b in s["by_over_bucket"].items():
        print(f"    {label:>8s} {b['n']:>8,d} {b['mean_real_score']:>11.1f} "
              f"{b['linear_slope_rpo_per_run']:>+10.5f} {b['slope_at_plus_10ish']:>+10.5f} "
              f"{b['quadratic_coef']:>+11.2e}")

    print(f"\n  [shape] partial dependence of E[runs] on {SCORE_COL}")
    pd_sample = sample if len(sample) <= 40000 else sample.sample(n=40000, random_state=11)
    out["partial_dependence"] = partial_dependence(model, pd_sample, fmt, args.pd_grid)
    for label, b in out["partial_dependence"]["by_over_bucket"].items():
        print(f"    overs {label:>7s}  score {b['score_range'][0]:6.1f}->{b['score_range'][1]:6.1f}  "
              f"slope {b.get('slope_rpo_per_run', float('nan')):+.5f} rpo/run  "
              f"monotone={b.get('monotone_increasing')}")

    if not args.skip_ablation:
        print(f"\n  [ablation] retraining the legal head out-of-fold (control / drop / replace)")
        out["ablation"] = run_ablation(fmt, frame, trajectory_vectors(traj),
                                       args.ablation_matches, args.ablation_folds)
        locked = {}
        if BASELINE_PATH.exists():
            locked = json.loads(BASELINE_PATH.read_text()).get(fmt, {})
        out["ablation"]["_locked_full_corpus_reference"] = {
            "legal_log_loss": locked.get("legal_log_loss"),
            "note": "context only -- not comparable to the subsampled control above",
        }
        for variant in ("drop", "replace"):
            mp = out["ablation"][variant]["match_paired"]
            print(f"    {variant:8s} vs control: {out['ablation'][variant]['delta_vs_control']:+.6f} "
                  f"log-loss  (match-paired t={mp['t']}, n={mp['n_matches']}, "
                  f"{mp['share_worse']:.0%} of matches worse)")
        if locked.get("legal_log_loss") is not None:
            print(f"    [context] locked full-corpus legal log-loss: {locked['legal_log_loss']:.6f}; "
                  f"gate tolerance +0.01")
    else:
        print("\n  [ablation] skipped (--skip-ablation)")

    path = OUT_DIR / f"score_feedback_{fmt}.json"
    path.write_text(json.dumps(out, indent=2, default=float))
    print(f"\n  Wrote {path}")
    return out


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    p.add_argument("--formats", nargs="+", default=["od", "t20"],
                   choices=["t20", "od", "hnd", "t20w", "odw", "hndw"])
    p.add_argument("--sample-deliveries", type=int, default=120000,
                   help="Legal deliveries sampled for the sensitivity/PD passes (0 = all).")
    p.add_argument("--deltas", type=float, nargs="+", default=DEFAULT_DELTAS,
                   help="Perturbations (runs) applied to current_team_score. Must include 0.")
    p.add_argument("--pd-grid", type=int, default=9, help="Grid points per partial-dependence curve.")
    p.add_argument("--ablation-matches", type=int, default=800,
                   help="Matches subsampled for the ablation retrain (0 = all; very slow).")
    p.add_argument("--ablation-folds", type=int, default=2,
                   help="How many of the 5 GroupKFold folds to actually train (precision vs time).")
    p.add_argument("--skip-ablation", action="store_true",
                   help="Sensitivity/shape/audit only -- no retraining.")
    args = p.parse_args()

    if 0.0 not in args.deltas:
        args.deltas = sorted(set(args.deltas) | {0.0})

    summary = {}
    for fmt in args.formats:
        t0 = time.time()
        summary[fmt] = run_format(fmt, args)
        print(f"  [{fmt}] done in {time.time() - t0:.0f}s\n", flush=True)

    print("=" * 78)
    print("CROSS-FORMAT SUMMARY")
    print("=" * 78)
    print(f"{'format':8s} {'rpo/run':>10s} {'slope@+10.68':>13s} {'drop Δll':>10s} {'replace Δll':>12s}")
    for fmt, r in summary.items():
        ab = r.get("ablation", {})
        d = ab.get("drop", {}).get("delta_vs_control")
        rp = ab.get("replace", {}).get("delta_vs_control")
        print(f"{fmt:8s} {r['sensitivity']['linear_slope_rpo_per_run']:>+10.5f} "
              f"{r['sensitivity']['slope_at_plus_10ish']:>+13.5f} "
              f"{('%+.6f' % d) if d is not None else 'n/a':>10s} "
              f"{('%+.6f' % rp) if rp is not None else 'n/a':>12s}")


if __name__ == "__main__":
    main()
