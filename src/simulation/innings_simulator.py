# Real cricket law: max overs per bowler = total_overs / 5 (4 in a T20, 10 in an ODI).
# The bowler-over schedule (see _build_bowler_schedule) never breaches that limit, and never
# repeats a bowler on consecutive overs. 5 is the fewest that can legally cover an innings --
# and with the old uniform quota, a 5-man attack meant all five bowling out, every innings.
MIN_BOWLERS_REQUIRED = 5

# How many bowlers squad builders should hand the simulator. Measured mean distinct bowlers per
# innings is 6.05-6.45 across the six formats, and the top 5 cover only ~92% of overs (top 6
# ~98.5%, top 7 ~99.9%) -- so 5 systematically forced ~8% of an innings onto bowlers who did not
# really bowl it. 7 is chosen over 6 because the taper makes the tail nearly free: rank 7 draws
# 0-1 overs, so when a squad has no genuine 7th bowler and the sort falls through to a batter,
# the cost is ~1 over rather than a full frontline share. Only meaningful WITH the taper -- 7
# bowlers on the old uniform quota would have handed that batter 7 of 50 overs.
ATTACK_SIZE = 7

